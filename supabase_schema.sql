-- 1. Create Profiles / Staff Table
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  email text unique not null,
  full_name text,
  role text not null default 'staff' check (role in ('admin', 'bursar', 'teacher', 'staff')),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable RLS on profiles
alter table public.profiles enable row level security;

-- Profiles Policies:
-- Any authenticated user can read their own profile
create policy "Users can view their own profile"
  on public.profiles for select
  to authenticated
  using ( (select auth.uid()) = id );

-- Users can update their own profile (with both USING and WITH CHECK)
create policy "Users can update their own profile"
  on public.profiles for update
  to authenticated
  using ( (select auth.uid()) = id )
  with check ( (select auth.uid()) = id );

-- Admins can view all profiles
create policy "Admins can view all profiles"
  on public.profiles for select
  to authenticated
  using (
    exists (
      select 1 from public.profiles
      where profiles.id = (select auth.uid())
      and profiles.role in ('admin', 'bursar')
    )
  );

-- 2. Automatically create profile row when a new user signs up
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, email, full_name, role)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
    coalesce(new.raw_app_meta_data->>'role', 'staff')
  );
  return new;
end;
$$;

-- Trigger on auth.users table
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- 3. Inquiries Table (Admission/Contact Inquiries)
create table if not exists public.inquiries (
  id bigint generated by default as identity primary key,
  full_name text not null,
  email text not null,
  phone text,
  subject text,
  message text not null,
  status text not null default 'Unread' check (status in ('Unread', 'Read', 'Replied')),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.inquiries enable row level security;

-- Public can submit inquiries
create policy "Anyone can submit inquiry"
  on public.inquiries for insert
  to anon, authenticated
  with check (true);

-- Authenticated staff can view inquiries
create policy "Staff can view inquiries"
  on public.inquiries for select
  to authenticated
  using (true);

-- Authenticated staff can update inquiries
create policy "Staff can update inquiries"
  on public.inquiries for update
  to authenticated
  using (true)
  with check (true);
